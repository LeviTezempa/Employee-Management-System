CREATE DATABASE IF NOT EXISTS mydatabase;
USE mydatabase;

CREATE TABLE IF NOT EXISTS employees (
  employeeID INT NOT NULL AUTO_INCREMENT,
  employeeFullName VARCHAR(255) DEFAULT NULL,
  employeeUsername VARCHAR(255) DEFAULT NULL,
  employeePassword VARCHAR(100) DEFAULT NULL,
  employeeEmail VARCHAR(100) DEFAULT NULL,
  employeePhone VARCHAR(10) DEFAULT NULL,
  employeeDepartment VARCHAR(255) DEFAULT NULL,
  employeeSex VARCHAR(100) DEFAULT NULL,
  PRIMARY KEY (employeeID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attendance (
  id INT NOT NULL AUTO_INCREMENT,
  employeeID INT DEFAULT NULL,
  timeIn VARCHAR(255) DEFAULT NULL,
  timeOut VARCHAR(100) DEFAULT NULL,
  date VARCHAR(100) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY employeeID_date (employeeID, date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
